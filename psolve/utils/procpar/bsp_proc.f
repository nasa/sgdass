      SUBROUTINE GET_NAM_FROM_HARPOS ( VTD, I_PSV, STA_NAM, I_STA, IUER  )
! ************************************************************************
! *                                                                      *
! *   Routine GET_NAM_FROM_HARPOS
! *                                                                      *
! *   Copyright (c) 1975-2026 United States Government as represented by *
! *   the Administrator of the National Aeronautics and Space            *
! *   Administration. All Rights Reserved.                               *
! *   License: NASA Open Source Software Agreement (NOSA).               *
! *                                                                      *
! * ## 03-AUG-2026 GET_NAM_FROM_HARPOS v1.0 (d) L. Petrov 03-AUG-2026 ## *
! *                                                                      *
! ************************************************************************
      IMPLICIT   NONE 
      INCLUDE   'vtd.i'
      TYPE     ( VTD__TYPE ) :: VTD
      INTEGER*4  I_PSV, I_STA, IUER
      CHARACTER  STA_NAM*(*)
      INTEGER*4  J1
      CHARACTER  STR*128
      INTEGER*4, EXTERNAL :: LTM_DIF
!
      IF ( I_PSV < 1 .OR. I_PSV > VTD__M_PSF ) THEN
           CALL CLRCH ( STR ) 
           CALL INCH  ( I_PSV, STR ) 
           CALL ERR_LOG ( 8541, IUER, 'GET_NAM_FROM_HARPOS', 'Trap '// &
     &         'of internal control: I_PSV argument is out of '// &
     &         'range [1 , VTD__M_PSF]: '//STR )
           RETURN 
      END IF
      IF ( .NOT. VTD%POSVAR(I_PSV)%STS_NAMSIT == PSV__REA ) THEN
           CALL CLRCH ( STR ) 
           CALL INCH  ( I_PSV, STR ) 
           CALL ERR_LOG ( 8542, IUER, 'GET_NAM_FROM_HARPOS', 'Trap '// &
     &         'of internal control: Names for the '//TRIM(STR)// &
     &         '-th position variations are note loaded' )
           RETURN 
      END IF
      IF ( VTD%POSVAR(I_PSV)%N_PSVSTA < 1 ) THEN
           CALL CLRCH ( STR ) 
           CALL INCH  ( I_PSV, STR ) 
           CALL ERR_LOG ( 8543, IUER, 'GET_NAM_FROM_HARPOS', 'Trap '// &
     &         'of internal control: the number of stations '// &
     &         'for the '//TRIM(STR)//'-th position variations is zero' )
           RETURN 
      END IF
!
      I_STA = LTM_DIF ( 0, VTD%POSVAR(I_PSV)%N_PSVSTA, &
     &                  %VAL(VTD%POSVAR(I_PSV)%ADR_NAMSIT), STA_NAM, %VAL(8) )
