      SUBROUTINE BSP_USE_HARPOS ( MJD_OBS, TAI_OBS, L_STA, L_HAR, I_STA, &
     &                            STA_TRS_COO, HARVAL, HARDSP, COO_HAR, IUER )
! ************************************************************************
! *                                                                      *
! *   Routine BSP_USE_HARPOS 
! *                                                                      *
! *   Copyright (c) 1975-2026 United States Government as represented by *
! *   the Administrator of the National Aeronautics and Space            *
! *   Administration. All Rights Reserved.                               *
! *   License: NASA Open Source Software Agreement (NOSA).               *
! *                                                                      *
! * ## 03-AUG-2026  BSP_USE_HARPOS  v1.0 (d) L. Petrov  08-AUG-2026 ###  *
! *                                                                      *
! ************************************************************************
      IMPLICIT   NONE 
      INCLUDE   'astro_constants.i'
      INTEGER*4  MJD_OBS, I_STA, L_STA, L_HAR, IUER 
      REAL*8     TAI_OBS, STA_TRS_COO(3,L_STA), HARVAL(3,L_HAR), &
     &           HARDSP(3,2,L_HAR,L_STA), COO_HAR(3)      
      REAL*8     UEN_TO_XYZ(3,3), UEN_VEC_IN(3), UEN_VEC_OUT(3), &
     &           XYZ_VEC_IN(3), XYZ_VEC_OUT(3), TIM_ARG, HAR_ARG
      INTEGER*4  J1, J2, J3, IER
!
      COO_HAR = 0.0
      CALL MAKE_UEN_TO_XYZ ( STA_TRS_COO(1,I_STA), UEN_TO_XYZ )
      DO 410 J1=1,L_HAR
         TIM_ARG = (MJD_OBS - J2000__MJD)*86400.0D0 + (TAI_OBS - 43200.0D0)
         HAR_ARG = ( HARVAL(3,J1)*TIM_ARG/2.0D0 + HARVAL(2,J1) )*TIM_ARG + &
     &               HARVAL(1,J1)
!
! ----- For each station get the cosine and sine component of the
! ----- displacement vector
!
        UEN_VEC_IN(1)  = HARDSP(1,1,J1,I_STA)*DCOS(HAR_ARG)
        UEN_VEC_IN(2)  = HARDSP(2,1,J1,I_STA)*DCOS(HAR_ARG)
        UEN_VEC_IN(3)  = HARDSP(3,1,J1,I_STA)*DCOS(HAR_ARG)
!
        UEN_VEC_OUT(1) = HARDSP(1,2,J1,I_STA)*DSIN(HAR_ARG)
        UEN_VEC_OUT(2) = HARDSP(2,2,J1,I_STA)*DSIN(HAR_ARG)
        UEN_VEC_OUT(3) = HARDSP(3,2,J1,I_STA)*DSIN(HAR_ARG)
!
! ----- Transform the displacement vector from the local topocentric
! ----- reference system to the crust-fixed reference system
!
        CALL MUL_MV_IV_V ( 3, 3, UEN_TO_XYZ, 3, &
     &                     UEN_VEC_IN, 3, XYZ_VEC_IN, IER )
        CALL MUL_MV_IV_V ( 3, 3, UEN_TO_XYZ, 3, &
     &                     UEN_VEC_OUT, 3, XYZ_VEC_OUT, IER )
!
! ----- Add the displacement to displacements computed before this
! ----- call of BSP_USE_HARPOS
!
        COO_HAR(1:3) = COO_HAR(1:3) + XYZ_VEC_IN(1:3) + XYZ_VEC_OUT(1:3)
 410  CONTINUE 
!
      CALL ERR_LOG ( 0, IUER )
      RETURN
      END  SUBROUTINE  BSP_USE_HARPOS  !#!#
